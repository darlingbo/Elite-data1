// Cloudflare Worker entry point.
//
// Wraps the OpenNext-generated worker (.open-next/worker.js) so the site can
// also run the scheduled jobs that Vercel Cron used to trigger (see the
// "crons" list in vercel.json). Each job calls the existing /api/cron/* route
// inside this same Worker with the CRON_SECRET bearer header, exactly like
// Vercel did, so the route code is unchanged.
//
// Two Cron Triggers are configured in wrangler.jsonc (Workers Free allows 5
// per account): "5 0 * * *" for sync-orders and "0 * * * *" (hourly), which
// is dispatched below by UTC hour. Ghana time is UTC, so times are unchanged.

// Generated by `opennextjs-cloudflare build`. This file is bundled by
// wrangler and excluded from tsconfig (the import only exists after a build).
import openNextWorker from "./.open-next/worker.js";

type Env = { CRON_SECRET?: string; SITE_URL?: string };

type ScheduledEvent = { cron: string; scheduledTime: number };

type ExecutionContext = { waitUntil(promise: Promise<unknown>): void };

type OpenNextWorker = {
  fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response>;
};

const worker = openNextWorker as OpenNextWorker;

/** Which /api/cron/* paths run for a given trigger time (UTC). */
function jobsFor(cron: string, when: Date): string[] {
  if (cron === "5 0 * * *") return ["/api/cron/sync-orders"];

  const hour = when.getUTCHours();
  const day = when.getUTCDate();
  const jobs: string[] = [];
  if (hour === 2) jobs.push("/api/cron/backup");
  if (hour === 6 || hour === 20) jobs.push("/api/cron/snapshot");
  if (hour === 7) jobs.push("/api/cron/daily-report");
  if (hour === 8 || hour === 20) jobs.push("/api/cron/security-check");
  // Vercel schedule "0 8 */3 * *" = 08:00 on days 1, 4, 7, …, 31.
  if (hour === 8 && (day - 1) % 3 === 0) jobs.push("/api/cron/keepalive");
  return jobs;
}

async function runJob(path: string, env: Env, ctx: ExecutionContext) {
  const origin = env.SITE_URL || "https://elitedata1.com";
  const request = new Request(new URL(path, origin), {
    headers: { authorization: `Bearer ${env.CRON_SECRET ?? ""}`, "user-agent": "cloudflare-cron" },
  });
  const response = await worker.fetch(request, env, ctx);
  console.log(`cron ${path} -> ${response.status}`);
}

export default {
  fetch(request: Request, env: Env, ctx: ExecutionContext) {
    return worker.fetch(request, env, ctx);
  },

  async scheduled(event: ScheduledEvent, env: Env, ctx: ExecutionContext) {
    const jobs = jobsFor(event.cron, new Date(event.scheduledTime));
    for (const path of jobs) {
      try {
        await runJob(path, env, ctx);
      } catch (error) {
        console.error(`cron ${path} failed`, error);
      }
    }
  },
};
